#!/usr/bin/env python3
"""从 folia-major 源码生成墙的槽位/让位表 Swift 文件。
源：src/components/wall/blockTemplates.ts（TEMPLATES 4x12）
    src/components/wall/blockReflows.ts（BLOCK_REFLOWS 4x12x12）
生成后逐表校验恰好铺满 12x8，不通过不写文件。禁止手改生成物。"""
import re, sys, pathlib

root = pathlib.Path.home() / "workspace/folia-deploy/folia-major/src/components/wall"
slot_re = re.compile(r"\{\s*x:\s*(\d+),\s*y:\s*(\d+),\s*cols:\s*(\d+),\s*rows:\s*(\d+)\s*\}")

def slots_of(path):
    return [tuple(int(v) for v in m) for m in slot_re.findall(path.read_text())]

templates_flat = slots_of(root / "blockTemplates.ts")
reflows_flat = slots_of(root / "blockReflows.ts")
assert len(templates_flat) == 48, f"templates {len(templates_flat)} != 48"
assert len(reflows_flat) == 576, f"reflows {len(reflows_flat)} != 576"

def covers(slots):
    grid = [[0]*12 for _ in range(8)]
    for x, y, c, r in slots:
        for dy in range(r):
            for dx in range(c):
                grid[y+dy][x+dx] += 1
    return all(v == 1 for row in grid for v in row)

templates = [templates_flat[i*12:(i+1)*12] for i in range(4)]
reflows = [[reflows_flat[(t*12+s)*12:(t*12+s)*12+12] for s in range(12)] for t in range(4)]
for t in templates: assert covers(t), "template not exact cover"
for t in reflows:
    for s in t: assert covers(s), "reflow not exact cover"

def fmt(slots):
    return "[" + ", ".join(f"BlockSlot(x: {x}, y: {y}, cols: {c}, rows: {r})" for x, y, c, r in slots) + "]"

out = []
out.append("// GENERATED by scripts/gen-wall-tables.py from folia-major blockTemplates.ts + blockReflows.ts. Do not hand-edit.")
out.append("import Foundation")
out.append("")
out.append("struct BlockSlot: Equatable {")
out.append("    let x: Int")
out.append("    let y: Int")
out.append("    let cols: Int")
out.append("    let rows: Int")
out.append("}")
out.append("")
out.append("enum WallTables {")
out.append("    /// 4 个基础模板 x 12 槽位（定向靠 WallGeometry 的反射变换，不预展开）。")
out.append("    static let templates: [[BlockSlot]] = [")
for t in templates:
    out.append(f"        {fmt(t)},")
out.append("    ]")
out.append("")
out.append("    /// 让位表：[模板][被展开槽位][12 槽位]，下标 = 原槽位（身份不变）。")
out.append("    static let reflows: [[[BlockSlot]]] = [")
for t in reflows:
    out.append("        [")
    for s in t:
        out.append(f"            {fmt(s)},")
    out.append("        ],")
out.append("    ]")
out.append("}")

dest = pathlib.Path.home() / "workspace/folia-deploy/ios-shell/Sources/Native/Core/Wall/WallTables.swift"
dest.write_text("\n".join(out) + "\n")
print(f"wrote {dest} ({dest.stat().st_size} bytes); all tables exact-cover verified")
